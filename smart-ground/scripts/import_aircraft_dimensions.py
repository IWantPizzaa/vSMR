"""Freeze the existing native length catalogue for the browser core.

No native data is modified. Four separately reviewed primary planning lengths
override this rounded catalogue in AircraftGeometry.ts.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT.parent / 'vSMR/data/aircraft_types.json'
data = json.loads(source.read_text(encoding='utf-8'))
lengths = {code: item['length'] for code, item in sorted(data.items()) if isinstance(item.get('length'), (int, float)) and 0 < item['length'] < 500}
out = ROOT / 'src/core/AircraftDimensions.ts'
out.write_text('/** Generated by scripts/import_aircraft_dimensions.py from the read-only native catalogue.\n'
               f' * Source SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
               ' * Values are native catalogue dimensions, not independently re-certified type data. */\n'
               'export const NATIVE_AIRCRAFT_LENGTHS: Readonly<Record<string, number>> = Object.freeze('
               + json.dumps(lengths, ensure_ascii=False, indent=2) + ');\n', encoding='utf-8')
print(f'{len(lengths)} native lengths -> {out}')
